function capitalize(str) {
    return str[0].toUpperCase() + str.slice(1);
}

export async function add_to_cards(pokemon_number) { 
    try {
        const response = await fetch(`https://pokeapi.co/api/v2/pokemon/${pokemon_number}`)
        if (!response.ok) {
            throw new Error(`HTTP error! Status: ${response.status}`);
        }
        const data = await response.json();
        cards.push({
            id: pokemon_number,
            name: capitalize(data.name),
            sprite: "./assets/" + pokemon_number + ".jpg"
        })
        console.log(cards)
    } catch (error) {
        console.error(pokemon_number, '- Failed to fetch data:', error)
    }
}

